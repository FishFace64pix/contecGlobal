function init360Viewer() {
  if (viewerCleanup) {
    viewerCleanup();
    viewerCleanup = null;
  }

  const container = document.getElementById('product-viewer-box');
  const imgs = document.querySelectorAll('.viewer-img');
  const overlay = document.getElementById('viewer-overlay');
  const dot = document.getElementById('viewer-progress-dot');
  const beneOverlay = document.getElementById('viewer-benefit-overlay');
  const beneTitle = document.getElementById('vbo-title');
  const beneDesc = document.getElementById('vbo-desc');
  if (!container || imgs.length < 2) return;

  let isDragging = false;
  let startX = 0;
  let currentIndex = 0;
  let lastTextIdx = -1;

  const updateVisuals = (idx) => {
    imgs.forEach((img, i) => {
      if (i === idx) img.classList.add('active');
      else img.classList.remove('active');
    });
    if (dot) {
      const pct = (idx / (imgs.length - 1)) * 100;
      dot.style.left = `${pct}%`;
    }

    if (beneOverlay && beneTitle && beneDesc) {
      // Map img index (0-6) to text index (1-6)
      const textIdx = Math.min(idx, 5) + 1;
      if (lastTextIdx !== textIdx) {
        beneOverlay.classList.remove('visible');
        setTimeout(() => {
          beneTitle.innerHTML = t('t360_title_' + textIdx);
          beneDesc.innerHTML = t('t360_desc_' + textIdx);
          beneOverlay.classList.add('visible');
        }, 150);
        lastTextIdx = textIdx;
      }
    }

    // SYNC TINT MASK
    const tint = document.getElementById('tint-overlay');
    if (tint && imgs[idx]) {
      tint.style.webkitMaskImage = `url('${imgs[idx].src}')`;
      tint.style.maskImage = `url('${imgs[idx].src}')`;
    }
  };

  // init load
  updateVisuals(0);

  const handleStart = (e) => {
    isDragging = true;
    startX = e.type === 'mousedown' ? e.pageX : e.touches[0].pageX;
    container.style.cursor = 'grabbing';
    if (overlay) overlay.classList.add('hidden');
  };

  const handleMove = (e) => {
    if (!isDragging) return;
    const x = e.type === 'mousemove' ? e.pageX : e.touches[0].pageX;
    const diff = x - startX;

    // Yüksek hassasiyetli gecikmesiz değişim
    if (Math.abs(diff) > 12) {
      if (diff > 0) currentIndex = (currentIndex + 1) % imgs.length;
      else currentIndex = (currentIndex - 1 + imgs.length) % imgs.length;

      updateVisuals(currentIndex);
      startX = x;
    }
  };

  const handleEnd = () => {
    isDragging = false;
    container.style.cursor = 'grab';
  };

  // Tüm container alanından sürüklemeyi yakala
  container.addEventListener('mousedown', handleStart);
  window.addEventListener('mousemove', handleMove, { passive: true });
  window.addEventListener('mouseup', handleEnd, { passive: true });

  container.addEventListener('touchstart', handleStart, { passive: true });
  window.addEventListener('touchmove', handleMove, { passive: true });
  window.addEventListener('touchend', handleEnd, { passive: true });

  // Initial tint sync if exists
  const tint = document.getElementById('tint-overlay');
  if (tint && imgs[0]) {
    tint.style.webkitMaskImage = `url('${imgs[0].src}')`;
    tint.style.maskImage = `url('${imgs[0].src}')`;
  }

  viewerCleanup = () => {
    container.removeEventListener('mousedown', handleStart);
    window.removeEventListener('mousemove', handleMove);
    window.removeEventListener('mouseup', handleEnd);
    container.removeEventListener('touchstart', handleStart);
    window.removeEventListener('touchmove', handleMove);
    window.removeEventListener('touchend', handleEnd);
  };
}

/* ===================== DYNAMIC COLOR TINTING ===================== */
window.applyProductColor = function (el, hex) {
  if (!el) return;

  // Update UI state
  const container = el.closest('.color-options');
  if (container) {
    container.querySelectorAll('.color-swatch').forEach(s => s.classList.remove('active'));
    el.classList.add('active');
  }

  // Local Detail Page Tint
  const tint = document.getElementById('tint-overlay');
  const imgs = document.querySelectorAll('.viewer-img');
  const activeImg = document.querySelector('.viewer-img.active');

  if (tint && activeImg) {
    tint.style.backgroundColor = hex;
    const isBottle = tint.classList.contains('bottle-tint');
    tint.style.opacity = (hex === 'transparent') ? '0' : (isBottle ? '0.65' : '0.85');
    tint.style.webkitMaskImage = `url('${activeImg.src}')`;
    tint.style.maskImage = `url('${activeImg.src}')`;

    // Apply grayscale to base images to allow perfect tinting
    imgs.forEach(img => {
      img.style.filter = (hex === 'transparent') ? '' : 'grayscale(1) brightness(1.1)';
    });
  }

  // Modal Tint Support
  const modalTint = document.getElementById('modal-tint-overlay');
  const modalImg = document.querySelector('.modal-image-side img');
  if (modalTint && modalImg) {
    modalTint.style.backgroundColor = hex;
    const isBottle = modalTint.classList.contains('bottle-tint');
    modalTint.style.opacity = hex === 'transparent' ? '0' : (isBottle ? '0.65' : '0.85');
    modalTint.style.webkitMaskImage = `url('${modalImg.src}')`;
    modalTint.style.maskImage = `url('${modalImg.src}')`;
    modalImg.style.filter = (hex === 'transparent') ? '' : 'grayscale(1) brightness(1.1)';
  }
};

