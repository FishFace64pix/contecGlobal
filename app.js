/* ===================== PAGE TRANSITION BUBBLES ===================== */
function triggerPageTransitionBubbles() {
  const container = document.createElement('div');
  container.className = 'page-transition-bubbles';
  document.body.appendChild(container);

  // Romanian Flag colors: Blue (#002B7F), Yellow (#FCD116), Red (#CE1126)
  const colors = ['#002B7F', '#FCD116', '#CE1126'];

  for (let i = 0; i < 45; i++) {
    const bubble = document.createElement('div');
    bubble.className = 'transition-bubble';
    bubble.style.left = Math.random() * 100 + 'vw';
    bubble.style.backgroundColor = colors[i % 3];
    bubble.style.animationDuration = (Math.random() * 2 + 1.5) + 's'; // 1.5s to 3.5s
    bubble.style.animationDelay = (Math.random() * 0.5) + 's';

    // Size variation
    const size = Math.random() * 25 + 10; // 10px to 35px
    bubble.style.width = size + 'px';
    bubble.style.height = size + 'px';

    // Horizontal sway offset
    const sway = (Math.random() * 100 - 50) + 'px';
    bubble.style.setProperty('--sway-x', sway);

    container.appendChild(bubble);
  }

  // Remove after animation finishes
  setTimeout(() => {
    if (document.body.contains(container)) {
      document.body.removeChild(container);
    }
  }, 4500);
}

/* ===================== ROUTER ===================== */
function route() {
  const hash = location.pathname || '/';
  const app = document.getElementById('app');
  let html = '';
  if (hash === '/') { html = renderHome(); }
  else if (hash === '/products') { html = renderProducts(); }
  else if (hash.startsWith('/products/')) { html = renderProductDetail(hash.replace('/products/', '')); }
  else if (hash === '/about') { html = renderAbout(); }
  else { html = renderHome(); }
  app.innerHTML = html;
  triggerPageTransitionBubbles();
  window.scrollTo(0, 0);
  updateNavActive(hash);
  updateSEO();
  // Toggle header transparency based on page
  const header = document.getElementById('site-header');
  if (hash === '/') { header.classList.add('on-hero'); }
  else { header.classList.remove('on-hero'); }
  if (hash !== '/' && particleCleanup) {
    particleCleanup();
    particleCleanup = null;
  }
  if (!hash.startsWith('/products/') && viewerCleanup) {
    viewerCleanup();
    viewerCleanup = null;
  }
  // Post-render hooks
  requestAnimationFrame(() => {
    if (hash === '/') initParticles(document.getElementById('hero-canvas'));
    if (window.observeElements) window.observeElements();
    initFAQs();
    initFormValidation();
    if (hash.startsWith('/products/')) init360Viewer();
  });
}

