/* ===================== FORM HANDLER & VALIDATION ===================== */
function initFormValidation() {
  const form = document.querySelector('.contact-form form');
  if (!form) return;

  const inputs = form.querySelectorAll('input[required], textarea[required]');
  inputs.forEach(input => {
    input.addEventListener('blur', () => {
      const group = input.closest('.form-group');
      if (!input.checkValidity()) {
        group.classList.add('has-error');
      } else {
        group.classList.remove('has-error');
      }
    });
    input.addEventListener('input', () => {
      const group = input.closest('.form-group');
      if (group.classList.contains('has-error') && input.checkValidity()) {
        group.classList.remove('has-error');
      }
    });
  });
}

window.handleFormSubmit = async function (event) {
  event.preventDefault();
  const form = event.target;

  // Custom Validation check (Validate-on-blur implementation per UI/UX guidelines)
  let isValid = true;
  const inputs = form.querySelectorAll('input[required]:not([type="checkbox"]), textarea[required]');
  inputs.forEach(input => {
    if (!input.checkValidity()) {
      input.closest('.form-group').classList.add('has-error');
      isValid = false;
    }
  });

  // Custom Phone Validation (Strict Country Code)
  const phone = form.querySelector('#cf-phone');
  if (phone && phone.value.trim().length > 0) {
    if (!/^\+[0-9]{8,15}$/.test(phone.value.trim().replace(/\s/g, ''))) {
      phone.closest('.form-group').classList.add('has-error');
      isValid = false;
    }
  }

  // GDPR Consent Validation
  const gdpr = form.querySelector('#cf-gdpr');
  if (gdpr && !gdpr.checked) {
    document.getElementById('gdpr-group').classList.add('has-error');
    isValid = false;
  }

  if (!isValid) return;

  const btn = form.querySelector('button');
  const status = document.getElementById('form-status');

  const originalBtnText = btn.innerHTML;
  btn.innerHTML = t('form_sending');
  btn.style.opacity = '0.7';
  btn.disabled = true;

  const data = new FormData(form);

  try {
    const response = await fetch(form.action, {
      method: "POST",
      body: data,
      headers: { 'Accept': 'application/json' }
    });

    if (response.ok) {
      status.innerHTML = t('form_success');
      status.style.color = '#10b981';
      status.style.display = 'block';
      form.reset();
    } else {
      status.innerHTML = t('form_error_server');
      status.style.color = '#ef4444';
      status.style.display = 'block';
    }
  } catch (error) {
    status.innerHTML = t('form_error_network');
    status.style.color = '#ef4444';
    status.style.display = 'block';
  }

  btn.innerHTML = originalBtnText;
  btn.style.opacity = '1';
  btn.disabled = false;
  setTimeout(() => { status.style.display = 'none'; }, 7000);
};

